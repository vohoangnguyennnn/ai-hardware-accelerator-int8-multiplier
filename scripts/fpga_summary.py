"""Combine Vivado results with the error metrics into tables and trade-off figures.

Inputs:
    results/fpga/fpga_results.csv   from fpga/scripts/run_sweep.py (real Vivado runs)
    results/error_metrics.csv       from scripts/error_analysis.py
Outputs (in --out, default results/fpga):
    fpga_summary.md                 Markdown table of every variant
    figures/luts_vs_mae.png         LUT cost vs. mean absolute error
    figures/fmax_vs_k.png           Fmax vs. truncation depth, with exact baselines

Usage:
    python scripts/fpga_summary.py
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

MODE_LABELS = {"none": "truncation only", "comp": "+ compensation", "compzg": "+ compensation + zero gate"}
SERIES = {"none": "#2a78d6", "comp": "#eb6834", "compzg": "#1baf7a"}
MARKERS = {"none": "o", "comp": "s", "compzg": "^"}
BASELINES = {"exact_lut": ("exact LUT (behavioral)", "-"), "exact_bw": ("exact Baugh-Wooley", "--"),
             "exact_dsp": ("exact DSP48E1", ":")}
INK, INK_2, MUTED, GRID, AXIS, SURFACE = "#0b0b0b", "#52514e", "#898781", "#e1e0d9", "#c3c2b7", "#fcfcfb"


def num(value: str) -> float | None:
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def load(fpga_csv: Path, metrics_csv: Path) -> list[dict]:
    metrics = {r["config"]: r for r in csv.DictReader(metrics_csv.open())}
    rows = []
    for r in csv.DictReader(fpga_csv.open()):
        m = metrics.get(r["variant"], {})
        exact = r["variant"].startswith("exact_")
        rows.append({**r, "mae": "0" if exact else m.get("mae", ""), "nmed": "0" if exact else m.get("nmed", ""),
                     "mred": "0" if exact else m.get("mred", "")})
    return rows


def write_markdown(rows: list[dict], path: Path, manifest: dict) -> None:
    def cell(value: str, fmt: str = "{}") -> str:
        v = num(value)
        return "-" if v is None else fmt.format(v)

    versions = ", ".join(manifest.get("vivado_version", [])) or "unknown"
    lines = [
        "<!-- Generated by scripts/fpga_summary.py from fpga_results.csv; do not edit by hand. -->",
        "",
        f"Vivado {versions}, part `{manifest.get('part', '?')}`, out-of-context, "
        f"registered inputs and output. Utilization and power: post-route at "
        f"{manifest.get('base_period_ns', '?')} ns. Fmax: tightest post-route run with WNS >= 0.",
        "",
        "| Variant | LUTs | FFs | CARRY4 | DSP | Fmax (MHz) | Data path at base (ns) | Logic levels | "
        "Dyn. power (W, est.) | MAE | NMED | Status |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['variant']} | {cell(r['slice_luts'], '{:.0f}')} | {cell(r['slice_registers'], '{:.0f}')} | "
            f"{cell(r['carry4'], '{:.0f}')} | {cell(r['dsp'], '{:.0f}')} | {cell(r['fmax_mhz'], '{:.1f}')} | "
            f"{cell(r['base_datapath_ns'], '{:.3f}')} | {cell(r['base_logic_levels'], '{:.0f}')} | "
            f"{r['power_dynamic_w'] or '-'} | {cell(r['mae'], '{:.3f}')} | {cell(r['nmed'], '{:.2e}')} | "
            f"{r['status']} |"
        )
    path.write_text("\n".join(lines) + "\n")


def _style(plt) -> None:
    plt.rcParams.update({
        "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
        "axes.edgecolor": AXIS, "axes.labelcolor": INK_2, "axes.titlecolor": INK, "axes.titlesize": 11,
        "axes.titleweight": "bold", "axes.titlelocation": "left", "axes.spines.top": False,
        "axes.spines.right": False, "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6,
        "xtick.color": MUTED, "ytick.color": MUTED, "xtick.labelcolor": INK_2, "ytick.labelcolor": INK_2,
        "legend.frameon": False, "legend.labelcolor": INK_2, "font.size": 9, "lines.linewidth": 2,
    })


def _tbw(rows: list[dict], mode: str, key: str) -> tuple[list[float], list[float], list[int]]:
    sel = [r for r in rows if r["rtl_module"] == "mul8s_tbw" and r["mode"] == mode and num(r[key]) is not None]
    sel.sort(key=lambda r: int(r["trunc_cols"]))
    return [num(r["mae"]) for r in sel], [num(r[key]) for r in sel], [int(r["trunc_cols"]) for r in sel]


def _baselines(ax, rows: list[dict], key: str, skip_zero: bool = False) -> None:
    by_name = {r["variant"]: r for r in rows}
    for name, (label, style) in BASELINES.items():
        value = num(by_name.get(name, {}).get(key))
        if value is None or (skip_zero and value == 0):
            continue
        ax.axhline(value, color=INK_2, linestyle=style, linewidth=1)
        ax.annotate(f"{label}: {value:.0f}", xy=(1.0, value), xycoords=("axes fraction", "data"),
                    xytext=(-4, 3), textcoords="offset points", ha="right", color=INK_2, fontsize=8)


def make_figures(rows: list[dict], fig_dir: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    _style(plt)
    fig_dir.mkdir(parents=True, exist_ok=True)

    fig, ax = plt.subplots(figsize=(7.6, 4.8), constrained_layout=True)
    for mode in MODE_LABELS:
        mae, luts, ks = _tbw(rows, mode, "slice_luts")
        pts = [(m, l, k) for m, l, k in zip(mae, luts, ks) if m and m > 0]
        if not pts:
            continue
        ax.plot([p[0] for p in pts], [p[1] for p in pts], color=SERIES[mode], marker=MARKERS[mode], markersize=6,
                markeredgecolor=SURFACE, markeredgewidth=1.2, label=f"mul8s_tbw, {MODE_LABELS[mode]}")
        if mode == "comp":
            for m, l, k in pts:
                ax.annotate(f"K={k}", xy=(m, l), xytext=(4, 4), textcoords="offset points", color=INK_2, fontsize=7)
    # The DSP baseline uses no LUTs, so it is omitted from the LUT axis.
    _baselines(ax, rows, "slice_luts", skip_zero=True)
    ax.set_xscale("log")
    ax.set_xlabel("Mean absolute error (LSB, log scale)")
    ax.set_ylabel("Slice LUTs (post-route)")
    ax.set_title("LUT cost vs. arithmetic error")
    fig.legend(loc="outside lower center", ncol=3)
    fig.savefig(fig_dir / "luts_vs_mae.png", dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(7.6, 4.8), constrained_layout=True)
    for mode in MODE_LABELS:
        _, fmax, ks = _tbw(rows, mode, "fmax_mhz")
        if ks:
            ax.plot(ks, fmax, color=SERIES[mode], marker=MARKERS[mode], markersize=6, markeredgecolor=SURFACE,
                    markeredgewidth=1.2, label=f"mul8s_tbw, {MODE_LABELS[mode]}")
    _baselines(ax, rows, "fmax_mhz")
    ax.set_xlabel("Truncated columns K")
    ax.set_ylabel("Fmax (MHz, post-route, WNS >= 0)")
    ax.set_xticks(range(8))
    ax.set_title("Maximum clock frequency vs. truncation depth")
    fig.legend(loc="outside lower center", ncol=3)
    fig.savefig(fig_dir / "fmax_vs_k.png", dpi=150)
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--fpga-csv", type=Path, default=ROOT / "results" / "fpga" / "fpga_results.csv")
    parser.add_argument("--metrics-csv", type=Path, default=ROOT / "results" / "error_metrics.csv")
    parser.add_argument("--out", type=Path, default=ROOT / "results" / "fpga")
    args = parser.parse_args()
    if not args.fpga_csv.exists():
        raise SystemExit(f"{args.fpga_csv} not found: run the Vivado sweep first (make fpga)")

    manifest_path = args.fpga_csv.parent / "run_manifest.json"
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else {}
    rows = load(args.fpga_csv, args.metrics_csv)
    args.out.mkdir(parents=True, exist_ok=True)
    write_markdown(rows, args.out / "fpga_summary.md", manifest)
    make_figures(rows, args.out / "figures")
    print(f"fpga_summary: {len(rows)} variants -> {args.out / 'fpga_summary.md'} and figures")


if __name__ == "__main__":
    main()
