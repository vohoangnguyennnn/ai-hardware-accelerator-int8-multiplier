def _style(plt) -> None:
    plt.rcParams.update({
        "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
        "axes.edgecolor": AXIS, "axes.labelcolor": INK_2, "axes.titlecolor": INK, "axes.titlesize": 11,
        "axes.titleweight": "bold", "axes.titlelocation": "left", "axes.spines.top": False,
        "axes.spines.right": False, "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6,
        "xtick.color": MUTED, "ytick.color": MUTED, "xtick.labelcolor": INK_2, "ytick.labelcolor": INK_2,
        "legend.frameon": False, "legend.labelcolor": INK_2, "font.size": 9, "lines.linewidth": 2,
    })


def plot_metrics_vs_k(plt, rows: list[dict], out: Path) -> None:
    fig, (ax_mae, ax_mred) = plt.subplots(1, 2, figsize=(9.6, 3.8), constrained_layout=True)
    for mode in approx_tbw.MODES:
        sel = [r for r in rows if r["mode"] == mode and r["trunc_cols"] > 0]
        k = [r["trunc_cols"] for r in sel]
        kw = dict(color=SERIES[mode], marker=MARKERS[mode], markersize=6, label=MODE_LABELS[mode],
                  markeredgecolor=SURFACE, markeredgewidth=1.2)
        ax_mae.plot(k, [r["mae"] for r in sel], **kw)
        ax_mred.plot(k, [100 * r["mred"] for r in sel], **kw)
    ax_mae.set_yscale("log")
    ax_mae.set_title("Mean absolute error")
    ax_mae.set_ylabel("MAE (LSB, log scale)")
    ax_mred.set_title("Mean relative error distance")
    ax_mred.set_ylabel("MRED (%)")
    for ax in (ax_mae, ax_mred):
        ax.set_xlabel("Truncated columns K")
        ax.set_xticks(range(1, 8))
    ax_mae.legend(loc="upper left")
    mae = {(r["mode"], r["trunc_cols"]): r["mae"] for r in rows}
    zg_delta = max(abs(mae[("compzg", k)] - mae[("comp", k)]) / mae[("comp", k)] for k in range(1, 8))
    ax_mred.text(4.0, 22, f"The two compensation curves overlap:\nthe zero gate changes MAE by at most {100 * zg_delta:.1f}%",
                 ha="center", color=INK_2, fontsize=8)
    fig.suptitle("mul8s_tbw error vs. truncation depth (all 65,536 operand pairs)", x=0.01, ha="left",
                 color=INK, fontsize=11)
    fig.savefig(out, dpi=150)
    plt.close(fig)


def plot_error_histograms(plt, a, b, exact, out: Path, k: int = 6) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(9.6, 3.6), sharey=True, constrained_layout=True)
    for ax, mode in zip(axes, ("none", "comp")):
        cfg = TbwConfig(k, comp_en=(mode == "comp"))
        e = approx_tbw.mul_tbw_vec(a, b, cfg) - exact
        values, counts = np.unique(e, return_counts=True)
        ax.bar(values, counts, width=1.0, color=SERIES[mode], linewidth=0)
        ax.axvline(e.mean(), color=INK, linewidth=1, linestyle="--")
        ax.annotate(f"bias = {e.mean():.2f}", xy=(e.mean(), counts.max()), xytext=(6, -4),
                    textcoords="offset points", color=INK, fontsize=8, va="top")
        ax.set_title(f"K = {k}, {MODE_LABELS[mode]}")
        ax.set_xlabel("Error e = P~ - P (LSB)")
    axes[0].set_ylabel("Operand pairs")
    fig.savefig(out, dpi=150)
    plt.close(fig)


def plot_error_heatmap(plt, a, b, exact, out: Path, k: int = 6) -> None:
    from matplotlib.colors import LinearSegmentedColormap, TwoSlopeNorm

    cfg = TbwConfig(k, comp_en=True)
    e = (approx_tbw.mul_tbw_vec(a, b, cfg) - exact).astype(float)
    # Re-order from vector-file index order to a signed grid: rows a = -128..127, cols b = -128..127.
    grid = np.empty((256, 256))
    grid[a + 128, b + 128] = e
    lim = np.abs(e).max()
    cmap = LinearSegmentedColormap.from_list("blue_gray_red", DIVERGING)
    fig, ax = plt.subplots(figsize=(5.6, 4.8), constrained_layout=True)
    img = ax.imshow(grid, origin="lower", extent=(-128.5, 127.5, -128.5, 127.5), cmap=cmap,
                    norm=TwoSlopeNorm(vmin=-lim, vcenter=0.0, vmax=lim), interpolation="nearest")
    ax.grid(False)
    ax.set_xlabel("b")
    ax.set_ylabel("a")
    ax.set_title(f"Error e(a, b), K = {k} + compensation")
    bar = fig.colorbar(img, ax=ax, shrink=0.85)
    bar.set_label("e (LSB)", color=INK_2)
    bar.outline.set_visible(False)
    fig.savefig(out, dpi=150)
    plt.close(fig)


def plot_relative_error_vs_magnitude(plt, a, b, exact, out: Path) -> None:
    nonzero = exact != 0
    mag = np.abs(exact[nonzero])
    edges = 2.0 ** np.arange(0, 15)  # [1, 2), [2, 4), ... [8192, 16384]
    centers = np.sqrt(edges[:-1] * edges[1:])
    fig, ax = plt.subplots(figsize=(6.4, 3.8), constrained_layout=True)
    # Colour follows the mode (as in the other figures); line style follows K.
    linestyles = {4: "-", 6: "--"}
    for k, mode in [(4, "none"), (4, "comp"), (6, "none"), (6, "comp")]:
        cfg = TbwConfig(k, comp_en=(mode == "comp"))
        rel = (np.abs(approx_tbw.mul_tbw_vec(a, b, cfg) - exact)[nonzero] / mag)
        idx = np.clip(np.digitize(mag, edges) - 1, 0, len(centers) - 1)
        mean_rel = np.array([rel[idx == i].mean() for i in range(len(centers))])
        ax.plot(centers, 100 * mean_rel, color=SERIES[mode], marker=MARKERS[mode], linestyle=linestyles[k],
                markersize=6, markeredgecolor=SURFACE, markeredgewidth=1.2, label=f"K = {k}, {MODE_LABELS[mode]}")
    ax.set_xscale("log", base=2)
    ax.set_yscale("log")
    ax.set_xlabel("|exact product| (octave bins)")
    ax.set_ylabel("Mean relative error (%, log scale)")
    ax.set_title("Relative error concentrates on small products")
    ax.legend(loc="upper right")
    fig.savefig(out, dpi=150)
    plt.close(fig)


def make_figures(rows: list[dict], a, b, exact, fig_dir: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    _style(plt)
    fig_dir.mkdir(parents=True, exist_ok=True)
    plot_metrics_vs_k(plt, rows, fig_dir / "metrics_vs_k.png")
    plot_error_histograms(plt, a, b, exact, fig_dir / "error_histogram_k6.png")
    plot_error_heatmap(plt, a, b, exact, fig_dir / "error_heatmap_k6_comp.png")
    plot_relative_error_vs_magnitude(plt, a, b, exact, fig_dir / "relative_error_vs_magnitude.png")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--no-figures", action="store_true", help="only write the CSV/Markdown tables")
    args = parser.parse_args()

    a, b = golden.all_pairs()
    exact = golden.mul_exact_vec(a, b)
    rows, quadrant_rows = compute(a, b, exact)

    args.out.mkdir(parents=True, exist_ok=True)
    write_csv(args.out / "error_metrics.csv", rows)
    write_markdown(args.out / "error_metrics.md", rows)
    write_csv(args.out / "error_by_quadrant.csv", quadrant_rows)
    if not args.no_figures:
        make_figures(rows, a, b, exact, args.out / "figures")
    print(f"error_analysis: {len(rows)} configurations written to {args.out}")


if __name__ == "__main__":
    main()
