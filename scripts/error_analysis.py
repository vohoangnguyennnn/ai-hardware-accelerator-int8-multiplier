"""Exhaustive error characterisation of every mul8s_tbw configuration.

Outputs (in --out):
    error_metrics.csv      one row per configuration (ER, MAE, NMED, MRED, bias, MSE)
    error_metrics.md       the same data as a Markdown table
    error_by_quadrant.csv  MAE / bias / MRED split by operand sign
    figures/*.png          metric trends and error distributions (unless --no-figures)

All numbers come from the bit-accurate model evaluated on all 65,536 operand
pairs. The RTL is verified bit-exact against the same model (make sim-tbw).

Usage:
    python scripts/error_analysis.py --out results
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from models import approx_tbw, golden, metrics  # noqa: E402
from models.approx_tbw import TbwConfig  # noqa: E402

QUADRANTS = (
    ("a>0,b>0", lambda a, b: (a > 0) & (b > 0)),
    ("a>0,b<0", lambda a, b: (a > 0) & (b < 0)),
    ("a<0,b>0", lambda a, b: (a < 0) & (b > 0)),
    ("a<0,b<0", lambda a, b: (a < 0) & (b < 0)),
    ("zero operand", lambda a, b: (a == 0) | (b == 0)),
)

MODE_LABELS = {"none": "truncation only", "comp": "+ compensation", "compzg": "+ compensation + zero gate"}

# Reference dataviz palette (categorical slots 1-3, chart chrome, blue/red diverging arms).
SERIES = {"none": "#2a78d6", "comp": "#eb6834", "compzg": "#1baf7a"}
MARKERS = {"none": "o", "comp": "s", "compzg": "^"}
INK, INK_2, MUTED, GRID, AXIS, SURFACE = "#0b0b0b", "#52514e", "#898781", "#e1e0d9", "#c3c2b7", "#fcfcfb"
DIVERGING = ["#104281", "#3987e5", "#9ec5f4", "#f0efec", "#f2aaa9", "#e34948", "#9c2626"]


def fmt(value: float) -> str:
    """Stable text form for CSV files (6 significant digits)."""
    if isinstance(value, (int, np.integer)):
        return str(int(value))
    if np.isnan(value):
        return ""
    return f"{value:.6g}"


def compute(a: np.ndarray, b: np.ndarray, exact: np.ndarray) -> tuple[list[dict], list[dict]]:
    rows, quadrant_rows = [], []
    for cfg in approx_tbw.all_configs():
        p = approx_tbw.mul_tbw_vec(a, b, cfg)
        comp = approx_tbw.comp_constant(cfg.trunc_cols) if cfg.comp_en else 0
        rows.append({"config": cfg.name, "trunc_cols": cfg.trunc_cols, "mode": cfg.mode, "comp_constant": comp,
                     **metrics.error_metrics(p, exact)})
        for label, select in QUADRANTS:
            sel = select(a, b)
            m = metrics.error_metrics(p[sel], exact[sel])
            quadrant_rows.append({"config": cfg.name, "trunc_cols": cfg.trunc_cols, "mode": cfg.mode, "operands": label,
                                  "n_pairs": m["n_pairs"], "mae": m["mae"], "bias": m["bias"], "mred": m["mred"]})
    return rows, quadrant_rows


def write_csv(path: Path, rows: list[dict]) -> None:
    with path.open("w", newline="", encoding="ascii") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow({k: fmt(v) if not isinstance(v, str) else v for k, v in row.items()})


def write_markdown(path: Path, rows: list[dict]) -> None:
    lines = [
        "<!-- Generated by scripts/error_analysis.py; do not edit by hand. -->",
        "",
        "| K | Mode | C | ER (%) | MAE | NMED | MRED (%) | Bias | MSE | Zero products wrong |",
        "|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        lines.append(
            f"| {r['trunc_cols']} | {r['mode']} | {r['comp_constant']} | {100 * r['er']:.2f} | {r['mae']:.3f} | "
            f"{r['nmed']:.2e} | {100 * r['mred']:.3f} | {r['bias']:.3f} | {r['mse']:.1f} | "
            f"{r['n_zero_exact_wrong']} / {r['n_zero_exact']} |"
        )
    path.write_text("\n".join(lines) + "\n", encoding="ascii")


